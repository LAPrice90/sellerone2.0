def get_f_output_contracts() -> Dict[str, FFileContract]:
    return dict(_OUTPUT_CONTRACTS)


def get_f_output_contract(name: str) -> FFileContract:
    if name not in _OUTPUT_CONTRACTS:
        available = ",".join(sorted(_OUTPUT_CONTRACTS.keys()))
        raise ValueError(f"unknown F output contract '{name}', expected one of: {available}")
    return _OUTPUT_CONTRACTS[name]


def get_f_output_column_types(name: str) -> Dict[str, str]:
    contract = get_f_output_contract(name)
    return {column: "string" for column in [*contract.required_columns, *contract.optional_columns]}
