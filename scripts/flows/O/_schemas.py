def get_o_output_contracts() -> Dict[str, OFileContract]:
    return dict(_OUTPUT_CONTRACTS)


def get_o_output_contract(name: str) -> OFileContract:
    if name not in _OUTPUT_CONTRACTS:
        available = ",".join(sorted(_OUTPUT_CONTRACTS.keys()))
        raise ValueError(f"unknown O output contract '{name}', expected one of: {available}")
    return _OUTPUT_CONTRACTS[name]


def core_truth_roles() -> Tuple[str, ...]:
    return _CORE_TRUTH_ROLES
