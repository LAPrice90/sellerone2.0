def _phase_detail(control_dir: Path) -> str:
    if not (control_dir / "QUEUE_CONTRACT.md").exists():
        return "control inventory complete; queue contract still missing"
    if not (control_dir / "STORAGE_POLICY.md").exists():
        return "queue contract complete; generated current state active; Custodian policy missing"
    if not (control_dir / "CURRENT_TICKETS.md").exists() or not (control_dir / "BACKLOG.md").exists():
        return "queue and Custodian policy exist; current tickets and backlog missing"
    if not (control_dir / "INSTRUCTION_CLEANUP_PLAN.md").exists():
        return "queue, Custodian policy, and current work files exist; instruction cleanup missing"
    if not (control_dir / "AI_USAGE.csv").exists():
        return "core control files and instruction bootstrap exist; AI usage report missing"
    if _coding_plan_archive_needed(control_dir):
        return "AI usage report exists; oversized legacy coding plan still needs archive"
    if _prompt_folder_archive_needed(control_dir):
        return "legacy coding plan archived; old plans and prompt folders still need template/history marking"
    if _role_file_trim_needed(control_dir):
        return "prompt folders archived; old role detail files still need trimming"
    if not (control_dir / "SKILL_SPECS.md").exists():
        return "role files trimmed; repeat workflows still need skill/template specs"
    if _storage_index_out_subtree_needed(control_dir):
        return "skill specs exist; mixed `out/` storage still needs subtree classification"
    if _custodian_dry_run_manifest_needed(control_dir):
        return "`out/` storage is classified; cleanup still needs a preview-only manifest"
    if _dead_automation_and_scheduler_review_needed(control_dir):
        return "cleanup manifest exists or is not required; dead automations and schedulers still need review"
    if _windows_scheduler_admin_pause_needed(control_dir):
        return "Windows scheduler pause is partially applied; elevated runtime tasks still need admin pause"
    if _windows_scheduler_pause_decision_needed(control_dir):
        return "dead automation review found ready Windows scheduler tasks; pause decision needed before automation rebuild"
    if _automation_rebuild_needed(control_dir):
        return "scheduler pause is complete; careful automation rebuild plan still needs to be generated"
    if _automation_activation_decision_needed(control_dir):
        if (control_dir / "SO21_REP_BRIEFING_PILOT.md").exists():
            return "paused Rep briefing pilot exists; activation decision is needed"
        return "automation rebuild plan exists; first pilot creation or activation decision is needed"
    if _rep_briefing_first_run_proof_needed(control_dir):
        return "Rep briefing pilot is active; first scheduled run proof is pending"
    return "core control files and AI usage visibility exist; ready for Git and system catch-up"


def _coding_plan_archive_needed(control_dir: Path) -> bool:
    root = control_dir.parents[1]
    coding_plan = root / "sellerone_manager" / "CODING_PLAN.md"
    archive_marker = control_dir / "CODING_PLAN_ARCHIVE.md"
    return coding_plan.exists() and coding_plan.stat().st_size >= 50_000 and not archive_marker.exists()


def _prompt_folder_archive_needed(control_dir: Path) -> bool:
    if (control_dir / "PROMPT_FOLDER_ARCHIVE.md").exists():
        return False
    rows = _read_csv_rows(control_dir / "AI_USAGE.csv")
    for row in rows:
        if row.get("job_ref") == "PLANS" and row.get("risk_level") == "high":
            return True
    return False


def _role_file_trim_needed(control_dir: Path) -> bool:
    if (control_dir / "ROLE_FILE_TRIM.md").exists():
        return False
    root = control_dir.parents[1]
    targets = [
        root / "sellerone_manager" / "MANAGER_CHAT.md",
        root / "sellerone_manager" / "MANAGER_PROGRESS_TRACKER.md",
        root / "sellerone_manager" / "CYCLE_SUB_MANAGER_CHAT.md",
        root / "sellerone_manager" / "WORKER_CHAT.md",
    ]
    return any(path.exists() and path.stat().st_size >= 10_000 for path in targets)


def _storage_index_out_subtree_needed(control_dir: Path) -> bool:
    path = control_dir / "STORAGE_INDEX.csv"
    if not path.exists():
        return False
    text = path.read_text(encoding="utf-8", errors="ignore").lower()
    return "needs out subtree index" in text or "needs out/ subtree index" in text


def _custodian_dry_run_manifest_needed(control_dir: Path) -> bool:
    return not (
        (control_dir / "CUSTODIAN_DRY_RUN_MANIFEST.csv").exists()
        or (control_dir / "CUSTODIAN_DRY_RUN_MANIFEST.md").exists()
    )


def _dead_automation_and_scheduler_review_needed(control_dir: Path) -> bool:
    return not (control_dir / "DEAD_AUTOMATION_AND_SCHEDULER_REVIEW.md").exists()


def _windows_scheduler_pause_decision_needed(control_dir: Path) -> bool:
    if (control_dir / "WINDOWS_SCHEDULER_PAUSE_DECISION.md").exists():
        return False
    rows = _read_csv_rows(control_dir / "DEAD_AUTOMATION_AND_SCHEDULER_REVIEW.csv")
