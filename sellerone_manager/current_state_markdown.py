def _format_problem_rows(title: str, rows: list[dict[str, Any]]) -> list[str]:
    lines = [f"## {title}", ""]
    if not rows:
        lines.extend(["- None visible in latest MOT evidence.", ""])
        return lines
    for row in rows[:5]:
        flow = _text(row.get("flow")) or "?"
        check = _text(row.get("check")) or _text(row.get("work_item_id")) or "unknown_check"
        root_cause = _text(row.get("root_cause_guess"))
        action = _text(row.get("manager_action"))
        summary = _text(row.get("summary"))
        value = _text(row.get("value"))
        detail = root_cause or action or summary or value or "No summary supplied."
        if action and action != detail:
            detail = f"{detail} Next: {action}"
        lines.append(f"- {flow} / {check}: {_shorten(detail, 190)}")
    lines.append("")
    return lines


def _format_work_rows(rows: list[dict[str, str]], *, empty_message: str) -> list[str]:
    if not rows:
        return [f"- {empty_message}"]
    lines = []
    for row in rows[:8]:
        status = STATUS_LABELS.get(row.get("status", ""), row.get("status", "unknown"))
        job_ref = _text(row.get("job_ref")) or _text(row.get("task_id")) or "unknown-job"
        title = _text(row.get("title")) or "Untitled ticket"
        flow = _text(row.get("flow")) or "?"
        luke = " Luke decision needed." if _text(row.get("luke_action_required")) == "1" else ""
        lines.append(f"- {job_ref} ({flow}, {status}): {_shorten(title, 120)}.{luke}")
    if len(rows) > 8:
        lines.append(f"- Plus {len(rows) - 8} more packet rows.")
    return lines


def _work_sort_key(row: dict[str, str]) -> tuple[int, int, str]:
    status_rank = {
        "blocked_needs_luke": 0,
        "retest_failed": 1,
        "fixed_needs_retest": 2,
        "in_progress": 3,
        "reopened": 4,
        "approved": 5,
        "parked": 6,
        "proved": 7,
    }.get(row.get("status", ""), 9)
    priority_rank = {"urgent": 0, "high": 1, "medium": 2, "low": 3}.get(row.get("priority", ""), 4)
    return status_rank, priority_rank, row.get("job_ref", row.get("task_id", ""))


def _toml_field(text: str, field: str) -> str:
    match = re.search(rf'^{re.escape(field)}\s*=\s*"([^"]*)"', text, flags=re.MULTILINE)
    return match.group(1) if match else ""


def _latest_observed(rows: list[dict[str, str]]) -> str:
    values = [row.get("observed_utc", "") for row in rows if row.get("observed_utc")]
    return max(values) if values else ""


def _status_from_counts(counts: Counter[str]) -> str:
    if counts.get("fail"):
        return "fail"
    if counts.get("decision_needed"):
        return "decision_needed"
    if counts.get("warn"):
        return "warn"
    if counts.get("ok"):
        return "ok"
    return "unknown"


def _int_text(value: object) -> str:
    if value is None:
        return "0"
    try:
        return str(int(value))
    except (TypeError, ValueError):
        return "0"


def _text(value: object) -> str:
    return str(value).strip() if value is not None else ""


def _shorten(value: str, limit: int) -> str:
    text = " ".join(value.split())
    if len(text) <= limit:
        return text
    return text[: max(0, limit - 3)].rstrip() + "..."


def _plural(value: object, singular: str) -> str:
    count = _int_text(value)
    suffix = "" if count == "1" else "s"
    if singular.endswith("y") and suffix:
        return f"{count} {singular[:-1]}ies"
    return f"{count} {singular}{suffix}"
