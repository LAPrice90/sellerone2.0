@dataclass(frozen=True)
class CurrentStateMarkdownResult:
    path: Path
    markdown: str
    generated_utc: str
    recommended_next_task: str
    active_automation_count: int
    active_work_count: int
    blocked_work_count: int


def utc_now_text() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def build_current_state_markdown(
    *,
    root: Path | str | None = None,
    generated_utc: str | None = None,
    automation_root: Path | str | None = None,
) -> CurrentStateMarkdownResult:
    paths = get_manager_paths(root)
    generated = generated_utc or utc_now_text()
    control_dir = paths.root / "sellerone_manager" / "CONTROL"
    state_path = paths.root / CONTROL_STATE_REL_PATH

    packet_rows = _read_csv_rows(paths.output_dir / "approved_task_packets.csv")
    mot_summary = _read_mot_summary(paths.output_dir / "mot")
    automation_summary = _read_automation_summary(automation_root, control_dir=control_dir)
    adr_summary = _read_architecture_decisions(control_dir / "ARCHITECTURE_DECISIONS.md")

    status_counts = Counter(row.get("status", "").strip() or "missing" for row in packet_rows)
    active_work = [
        row
        for row in packet_rows
        if row.get("status") in ACTIVE_STATUSES and _text(row.get("luke_action_required")) != "1"
    ]
    blocked_work = [
        row
        for row in packet_rows
        if row.get("status") in BLOCKED_STATUSES or _text(row.get("luke_action_required")) == "1"
    ]
    active_work = sorted(active_work, key=_work_sort_key)
    blocked_work = sorted(blocked_work, key=_work_sort_key)

    archive_path = paths.root / "sellerone_manager" / "tasks" / "archive"
    recommended_next = _recommended_next_task(
        control_dir=control_dir,
        unapproved_active_automation_count=automation_summary["unapproved_active_count"],
    )
    phase_detail = _phase_detail(control_dir)

    plain_status = _plain_status(
        mot_summary=mot_summary,
        active_automation_count=automation_summary["active_count"],
        approved_active_automation_count=automation_summary["approved_active_count"],
        unapproved_active_automation_count=automation_summary["unapproved_active_count"],
        active_work_count=len(active_work),
        blocked_work_count=len(blocked_work),
        recommended_next=recommended_next,
    )

    lines = [
        "# SellerOne Current State",
        "",
        f"Generated UTC: {generated}",
        "Generated by: `sellerone_manager.current_state_markdown`",
        "",
        "## Plain-English Status",
        "",
        plain_status,
        "",
        "## Current Phase",
        "",
        "- Phase: `SellerOne 2.1 - Control Desk Stabilisation`",
        f"- Detail: {phase_detail}",
        "- Operating shape: Luke talks to Rep; Operations reports feed Rep; queue owns work; Builders and Reviewers work tickets.",
        "",
        "## Queue Summary",
        "",
        "- Canonical queue: approved task packet system",
        "- Queue source: `sellerone_manager/tasks/` plus generated packet index",
        f"- Packet index rows: {len(packet_rows)}",
        f"- Approved: {status_counts.get('approved', 0)}",
        f"- In progress: {status_counts.get('in_progress', 0)}",
        f"- Waiting proof: {status_counts.get('fixed_needs_retest', 0)}",
        f"- Proof failed: {status_counts.get('retest_failed', 0)}",
        f"- Reopened: {status_counts.get('reopened', 0)}",
        f"- Luke-blocked: {status_counts.get('blocked_needs_luke', 0)}",
        f"- Parked: {status_counts.get('parked', 0)}",
        f"- Proved: {status_counts.get('proved', 0)}",
        f"- Archive folder: {'present' if archive_path.exists() else 'missing'}",
        "",
        "## Health Summary",
        "",
        f"- Latest MOT observed UTC: {mot_summary['observed_utc']}",
        f"- MOT status: `{mot_summary['status']}`",
        f"- Fails: {mot_summary['fail_count']}",
        f"- Warnings: {mot_summary['warn_count']}",
        f"- Decisions: {mot_summary['decision_count']}",
        f"- Not checked: {mot_summary['not_checked_count']}",
        "",
    ]
    lines.extend(_format_problem_rows("Top Failed Checks", mot_summary["fail_rows"]))
    lines.extend(_format_problem_rows("Top Decision Checks", mot_summary["decision_rows"]))
    lines.extend(
        [
            "## Active Work",
            "",
        ]
    )
    lines.extend(_format_work_rows(active_work, empty_message="No active Builder work is currently ready in the packet index."))
    lines.extend(
        [
            "",
            "## Blocked Work",
            "",
        ]
    )
    lines.extend(_format_work_rows(blocked_work, empty_message="No Luke-blocked packets are currently visible in the packet index."))
    lines.extend(
        [
            "",
            "## Operations State",
            "",
            f"- Codex automations found: {automation_summary['total_count']}",
            f"- Active automations: {automation_summary['active_count']}",
            f"- Approved active pilot automations: {automation_summary['approved_active_count']}",
            f"- Unapproved active automations: {automation_summary['unapproved_active_count']}",
            f"- Paused automations: {automation_summary['paused_count']}",
            f"- Architecture decisions recorded: {adr_summary['count']}",
        ]
    )
    if adr_summary["latest"]:
        lines.append(f"- Latest architecture decision: {adr_summary['latest']}")
    if automation_summary["approved_active_names"]:
        lines.extend(["", "Approved active pilot automations:"])
        for name in automation_summary["approved_active_names"][:5]:
            lines.append(f"- {name}")
    if automation_summary["unapproved_active_names"]:
        lines.extend(["", "Active automations needing review:"])
        for name in automation_summary["unapproved_active_names"][:5]:
            lines.append(f"- {name}")
    lines.extend(
        [
            "",
            "## Recommended Next Task",
            "",
            f"- `{recommended_next}`",
            f"- Reason: {_recommended_reason(recommended_next)}",
            "",
            "## Protected Boundaries",
            "",
        ]
    )
    for boundary in PROTECTED_BOUNDARIES:
        lines.append(f"- {boundary}")
    lines.extend(
        [
            "",
            "## Evidence Inputs",
            "",
            "- MOT evidence: `out/systems/M/mot/`",
            "- Packet index: `out/systems/M/approved_task_packets.csv`",
            "- Blocked packet evidence: packet status and `sellerone_manager/tasks/blocked/`",
            "- Automation state: Codex app automation definitions",
            "- Architecture decisions: `sellerone_manager/CONTROL/ARCHITECTURE_DECISIONS.md`",
            "",
            "## State Rule",
            "",
            "`CURRENT_STATE.md` is the human-readable state anchor. `current_state.json` is machine support only and must not outrank newer MOT or packet evidence.",
        ]
    )

    markdown = "\n".join(lines).rstrip() + "\n"
    return CurrentStateMarkdownResult(
        path=state_path,
        markdown=markdown,
        generated_utc=generated,
        recommended_next_task=recommended_next,
        active_automation_count=automation_summary["active_count"],
        active_work_count=len(active_work),
        blocked_work_count=len(blocked_work),
    )


def write_current_state_markdown(
    *,
    root: Path | str | None = None,
    generated_utc: str | None = None,
    automation_root: Path | str | None = None,
) -> CurrentStateMarkdownResult:
    result = build_current_state_markdown(root=root, generated_utc=generated_utc, automation_root=automation_root)
    result.path.parent.mkdir(parents=True, exist_ok=True)
    result.path.write_text(result.markdown, encoding="utf-8")
    return result


def format_current_state_markdown_status(result: CurrentStateMarkdownResult) -> str:
    return "\n".join(
        [
            "status=written",
            f"path={result.path}",
            f"generated_utc={result.generated_utc}",
            f"recommended_next_task={result.recommended_next_task}",
            f"active_automations={result.active_automation_count}",
            f"active_work={result.active_work_count}",
            f"blocked_work={result.blocked_work_count}",
        ]
    )


def _read_csv_rows(path: Path) -> list[dict[str, str]]:
    if not path.exists():
        return []
    with path.open("r", newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        return [{key: value or "" for key, value in row.items()} for row in reader]


def _read_json(path: Path) -> dict[str, Any]:
    if not path.exists():
        return {}
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return {}
    return payload if isinstance(payload, dict) else {}


def _read_mot_summary(mot_dir: Path) -> dict[str, Any]:
    json_payload = _read_json(mot_dir / "mot_latest.json")
    if json_payload:
        rows = json_payload.get("rows") if isinstance(json_payload.get("rows"), list) else []
        fail_rows = [row for row in rows if isinstance(row, dict) and row.get("status") == "fail"]
        decision_rows = [
            row
            for row in rows
            if isinstance(row, dict) and (row.get("status") == "decision_needed" or row.get("luke_action_required") == "1")
        ]
        return {
            "observed_utc": _text(json_payload.get("observed_utc")) or "unknown",
            "status": _text(json_payload.get("status")) or "unknown",
            "fail_count": _int_text(json_payload.get("fail_count")),
            "warn_count": _int_text(json_payload.get("warn_count")),
            "decision_count": _int_text(json_payload.get("decision_count")),
            "not_checked_count": _int_text(json_payload.get("not_checked_count")),
            "fail_rows": fail_rows[:5],
            "decision_rows": decision_rows[:5],
        }

    rows = _read_csv_rows(mot_dir / "mot_latest.csv")
    counts = Counter(row.get("status", "missing") for row in rows)
    fail_rows = [row for row in rows if row.get("status") == "fail"]
    decision_rows = [
        row for row in rows if row.get("status") == "decision_needed" or row.get("luke_action_required") == "1"
    ]
    return {
        "observed_utc": _latest_observed(rows) or "missing",
        "status": _status_from_counts(counts),
        "fail_count": str(counts.get("fail", 0)),
        "warn_count": str(counts.get("warn", 0)),
        "decision_count": str(counts.get("decision_needed", 0) + len([row for row in rows if row.get("luke_action_required") == "1"])),
        "not_checked_count": str(counts.get("not_checked", 0)),
        "fail_rows": fail_rows[:5],
        "decision_rows": decision_rows[:5],
    }


def _read_automation_summary(automation_root: Path | str | None, *, control_dir: Path) -> dict[str, Any]:
    root = _resolve_automation_root(automation_root)
    rows: list[dict[str, str]] = []
    if root and root.exists():
        for path in sorted(root.rglob("automation.toml")):
            text = path.read_text(encoding="utf-8", errors="ignore")
            rows.append(
                {
                    "id": _toml_field(text, "id") or path.parent.name,
                    "name": _toml_field(text, "name") or path.parent.name,
                    "status": _toml_field(text, "status") or "unknown",
                }
            )
    counts = Counter(row["status"] for row in rows)
    active_rows = [row for row in rows if row["status"] == "ACTIVE"]
    rep_briefing_activation_exists = (control_dir / "SO21_REP_BRIEFING_ACTIVATION.md").exists()
    cleanup_monitor_review_exists = (control_dir / "SO21_AUTOMATION_REVIEW.md").exists()
    approved_active_rows = [
        row
        for row in active_rows
        if _is_approved_active_pilot(
            row,
            rep_briefing_activation_exists=rep_briefing_activation_exists,
            cleanup_monitor_review_exists=cleanup_monitor_review_exists,
        )
    ]
    unapproved_active_rows = [
        row
        for row in active_rows
        if not _is_approved_active_pilot(
            row,
            rep_briefing_activation_exists=rep_briefing_activation_exists,
            cleanup_monitor_review_exists=cleanup_monitor_review_exists,
        )
    ]
    return {
        "total_count": len(rows),
        "active_count": counts.get("ACTIVE", 0),
        "approved_active_count": len(approved_active_rows),
        "unapproved_active_count": len(unapproved_active_rows),
        "paused_count": counts.get("PAUSED", 0),
        "approved_active_names": [row["name"] for row in approved_active_rows],
        "unapproved_active_names": [row["name"] for row in unapproved_active_rows],
    }


def _is_approved_active_pilot(
    row: dict[str, str],
    *,
    rep_briefing_activation_exists: bool,
    cleanup_monitor_review_exists: bool,
) -> bool:
    value = f"{row.get('id', '')} {row.get('name', '')}".lower()
    if "so21-rep-briefing" in value:
        return rep_briefing_activation_exists
    if "so21-cleanup-operations-monitor" in value or "so21 cleanup operations monitor" in value:
        return cleanup_monitor_review_exists
    return False


def _resolve_automation_root(automation_root: Path | str | None) -> Path | None:
    if automation_root is not None:
        return Path(automation_root)
    codex_home = os.environ.get("CODEX_HOME")
    if codex_home:
        return Path(codex_home) / "automations"
    user_profile = os.environ.get("USERPROFILE")
    if user_profile:
        return Path(user_profile) / ".codex" / "automations"
    return None


def _read_architecture_decisions(path: Path) -> dict[str, Any]:
    if not path.exists():
        return {"count": 0, "latest": ""}
    titles = []
    for line in path.read_text(encoding="utf-8", errors="ignore").splitlines():
        if line.startswith("## ADR-"):
            titles.append(line.removeprefix("## ").strip())
    return {"count": len(titles), "latest": titles[-1] if titles else ""}


